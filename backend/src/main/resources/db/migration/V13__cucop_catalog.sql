-- ADR-0017/ADR-0020: catálogo CUCoP de cuatro niveles (catalog-database-proposal, "Jerarquía CUCoP").
-- Valores de specs/domain/catalog-values.md (catálogos 14 a 17) con sus IDs originales. Cada hijo
-- referencia a su padre inmediato; todo nodo tiene al menos una partida específica (catalogs.md).

create table cucop_chapter (
    id          integer      not null primary key,
    key         varchar(50)  not null,
    description varchar(500) not null,
    level       integer      not null,
    constraint cucop_chapter_key_uk unique (key),
    constraint cucop_chapter_level_check check (level = 1)
);

create table cucop_concept (
    id          integer      not null primary key,
    chapter_id  integer      not null,
    key         varchar(50)  not null,
    description varchar(500) not null,
    level       integer      not null,
    constraint cucop_concept_key_uk unique (key),
    constraint cucop_concept_level_check check (level = 2),
    constraint cucop_concept_chapter_fk foreign key (chapter_id) references cucop_chapter (id)
);

create index cucop_concept_chapter_id_idx on cucop_concept (chapter_id);

create table cucop_generic_item (
    id          integer      not null primary key,
    concept_id  integer      not null,
    key         varchar(50)  not null,
    description varchar(500) not null,
    level       integer      not null,
    constraint cucop_generic_item_key_uk unique (key),
    constraint cucop_generic_item_level_check check (level = 3),
    constraint cucop_generic_item_concept_fk foreign key (concept_id) references cucop_concept (id)
);

create index cucop_generic_item_concept_id_idx on cucop_generic_item (concept_id);

create table cucop_specific_item (
    id              integer      not null primary key,
    generic_item_id integer      not null,
    key             varchar(50)  not null,
    description     varchar(500) not null,
    level           integer      not null,
    constraint cucop_specific_item_key_uk unique (key),
    constraint cucop_specific_item_level_check check (level = 4),
    constraint cucop_specific_item_generic_item_fk foreign key (generic_item_id) references cucop_generic_item (id)
);

create index cucop_specific_item_generic_item_id_idx on cucop_specific_item (generic_item_id);

